"""Generate per-class map colours grouped into composition categories.

Usage: python scripts/generate_class_shades.py public/data/asteroids.json > lib/asteroids/class-shades.ts

Each asteroid is placed in a category from its class and albedo (same rule as
asteroidCategory() in lib/asteroids/class-colors.ts). Every (class, category)
pair that occurs gets its own shade: categories own a hue range and lightness
band (OKLCH), and the pairs inside are spread across it, most common first.
"""
import json, math, re, sys
from collections import Counter

# Keep in sync with asteroidCategory() in lib/asteroids/class-colors.ts
LETTER = {'M': 'metallic', **{c: 'silicate' for c in 'SQAKLROVE'}, **{c: 'carbon' for c in 'CBFGDPTZ'}}
PRIMITIVE = set('DPTZ')
TYPICAL = {'carbon': 0.06, 'metallic': 0.18, 'silicate': 0.25}

def candidates(name):
    out = []
    for ch in re.sub(r'[^A-Z]', '', name or ''):
        for c in (['carbon', 'metallic', 'silicate'] if ch == 'X' else [LETTER.get(ch)]):
            if c and c not in out:
                out.append(c)
    return out

def asteroid_category(name, albedo):
    cand = candidates(name)
    if not cand:
        return 'unknown'
    if len(cand) == 1:
        return cand[0]
    caps = re.sub(r'[^A-Z]', '', name)
    if albedo is None:
        return 'carbon' if caps[0] == 'X' else LETTER.get(caps[0], cand[0])
    if albedo < 0.1:
        pref = ['carbon']
    elif albedo > 0.3:
        pref = ['silicate']
    else:
        pref = ['metallic'] if caps == 'X' else ['silicate', 'metallic']
    for c in pref:
        if c in cand:
            return c
    return min(cand, key=lambda c: abs(TYPICAL[c] - albedo))

# (hue start, hue end, chroma, lightness levels) in OKLCH. Each family has its own
# lightness band as well as hue range, so categories stay apart for colour-blind
# viewers too (hue alone confuses e.g. pink/blue for protanopes).
FAMILIES = {
    'metallic':  (25, 90, 0.17, [0.74, 0.66, 0.82]),
    'silicate':  (142, 178, 0.16, [0.84, 0.78, 0.9, 0.81, 0.87, 0.75, 0.92]),
    'carbon':    (238, 268, 0.17, [0.62, 0.55, 0.68, 0.58, 0.65, 0.52, 0.71]),   # C-complex blues
    'primitive': (282, 305, 0.15, [0.58, 0.66, 0.52, 0.62]),                     # D/P/T/Z violets, still Carbon
    'unknown':   (0, 0, 0.0, [0.55, 0.65]),
}

def oklch_to_srgb(L, C, h):
    a, b = C * math.cos(math.radians(h)), C * math.sin(math.radians(h))
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_ ** 3, m_ ** 3, s_ ** 3
    rgb = [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
           -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
           -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s]
    def enc(x):
        return 12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055
    return [enc(x) for x in rgb]

def in_gamut(L, C, h):
    return all(-1e-4 <= v <= 1 + 1e-4 for v in oklch_to_srgb(L, C, h))

def hex_colour(L, C, h):
    while C > 0 and not in_gamut(L, C, h):
        C -= 0.005
    r, g, b = (min(1, max(0, v)) for v in oklch_to_srgb(L, C, h))
    return '#%02X%02X%02X' % (round(r * 255), round(g * 255), round(b * 255))

def main():
    records = json.load(open(sys.argv[1]))
    counts = Counter()
    for r in records:
        name = r.get('taxonomy_class') or 'Unclassified'
        counts[(name, asteroid_category(None if name == 'Unclassified' else name, r.get('albedo')))] += 1

    groups = {}
    for (name, cat), n in counts.most_common():
        fam = 'primitive' if cat == 'carbon' and name[0] in PRIMITIVE and len(candidates(name)) == 1 else cat
        groups.setdefault(fam, []).append((name, cat))

    shades = {}
    order = [0.5, 0.15, 0.85, 0.33, 0.67, 0.0, 1.0]
    for fam, pairs in groups.items():
        h0, h1, chroma, levels = FAMILIES[fam]
        k = len(pairs)
        for i, pair in enumerate(pairs):
            L = levels[i % len(levels)]
            frac = order[i] if i < len(order) else (i / max(k - 1, 1))
            shades[pair] = hex_colour(L, chroma, h0 + (h1 - h0) * frac)

    print('// Generated by scripts/generate_class_shades.py; do not edit by hand.')
    print('// Keys are "class|category"; mixed classes (e.g. X, CX) have one entry per category.')
    print('export const CLASS_SHADES: Record<string, string> = {')
    for (name, cat) in sorted(shades, key=lambda p: (p[1], -counts[p])):
        print(f"  {json.dumps(name + '|' + cat)}: '{shades[(name, cat)]}', // {counts[(name, cat)]}")
    print('}')


if __name__ == '__main__':
    main()
